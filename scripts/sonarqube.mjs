#!/usr/bin/env node
/* eslint-disable no-console */

/**
 * Generates the root `sonar-project.properties` for SonarQube Cloud (#2248).
 * The analysis scope is derived from the root `package.json` workspaces with
 * the same production-source rules as the duplication scan, so a new plugin
 * or bootstrap file can't silently fall out of the analysis.
 *
 *   npm run sonarqube:config      rewrite sonar-project.properties
 *   npm run validate:sonarqube    fail when the committed file is stale
 *
 * The organization and project key are not in the file: the workflow passes
 * them from repository variables. SONARQUBE.md explains the setup.
 */

import { lstatSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import {
	EXCLUDED_DIRS,
	LANGUAGES,
	ROOT,
	SOURCE_DIRS,
	readWorkspaces,
} from './duplication.mjs';

export const PROPERTIES_FILE = 'sonar-project.properties';

// Generated or test files that can sit next to production code.
export const EXCLUDED_FILE_PATTERNS = [
	...LANGUAGES.javascript.flatMap((ext) => [
		`**/*.test.${ext}`,
		`**/*.spec.${ext}`,
	]),
	'**/*.asset.php',
	'**/*.min.js',
];

function isDirectory(full) {
	return lstatSync(full, { throwIfNoEntry: false })?.isDirectory() ?? false;
}

/**
 * Analysis roots: each workspace's top-level PHP bootstrap files and its
 * existing production source directories, as sorted repo-relative paths.
 */
export function discoverSourceRoots(root, workspaces) {
	const roots = [];
	for (const workspace of workspaces) {
		const dir = path.join(root, workspace);
		if (!isDirectory(dir)) {
			throw new Error(`Workspace directory not found: ${workspace}`);
		}
		for (const entry of readdirSync(dir, { withFileTypes: true })) {
			if (entry.isFile() && entry.name.endsWith('.php')) {
				roots.push(`${workspace}/${entry.name}`);
			}
		}
		for (const source of SOURCE_DIRS) {
			if (isDirectory(path.join(dir, source))) {
				roots.push(`${workspace}/${source}`);
			}
		}
	}
	if (roots.length === 0) {
		throw new Error('No source roots found for SonarQube analysis.');
	}
	return roots.sort();
}

function list(key, values) {
	return [
		`${key}=\\`,
		...values.map((value, index) => {
			const last = index === values.length - 1;
			return `    ${value}${last ? '' : ',\\'}`;
		}),
	].join('\n');
}

export function renderProperties(sourceRoots) {
	const extensions = Object.values(LANGUAGES).flat();
	return `${[
		'# Generated by `npm run sonarqube:config` (scripts/sonarqube.mjs).',
		'# Do not edit by hand; see SONARQUBE.md. The organization and project',
		'# key come from repository variables in .github/workflows/sonarqube.yml.',
		'',
		'sonar.sourceEncoding=UTF-8',
		'',
		'# Maintained production code of every root package.json workspace.',
		list('sonar.sources', sourceRoots),
		'',
		'# PHP and JavaScript only.',
		list(
			'sonar.inclusions',
			extensions.map((ext) => `**/*.${ext}`)
		),
		`sonar.javascript.file.suffixes=${LANGUAGES.javascript
			.map((ext) => `.${ext}`)
			.join(',')}`,
		'',
		'# Dependencies, generated output, SVN copies, translations, reports,',
		'# fixtures, mocks and tests.',
		list('sonar.exclusions', [
			...[...EXCLUDED_DIRS].map((dir) => `**/${dir}/**`),
			...EXCLUDED_FILE_PATTERNS,
		]),
	].join('\n')}\n`;
}

export function generate(root) {
	return renderProperties(discoverSourceRoots(root, readWorkspaces(root)));
}

/**
 * Returns `null` when the committed file matches, otherwise a message.
 */
export function check(root) {
	const expected = generate(root);
	let actual;
	try {
		actual = readFileSync(path.join(root, PROPERTIES_FILE), 'utf8');
	} catch {
		return `${PROPERTIES_FILE} is missing. Run \`npm run sonarqube:config\`.`;
	}
	return actual === expected
		? null
		: `${PROPERTIES_FILE} is out of date. Run \`npm run sonarqube:config\` and commit the result.`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const [command = 'check', ...rest] = process.argv.slice(2);
	try {
		if (rest.length > 0 || !['check', 'write'].includes(command)) {
			throw new Error('Usage: node scripts/sonarqube.mjs [check|write]');
		}
		if (command === 'write') {
			writeFileSync(path.join(ROOT, PROPERTIES_FILE), generate(ROOT));
			console.log(`Wrote ${PROPERTIES_FILE}.`);
		} else {
			const problem = check(ROOT);
			if (problem) {
				console.error(problem);
				process.exit(1);
			}
			console.log(`${PROPERTIES_FILE} is up to date.`);
		}
	} catch (error) {
		console.error(`SonarQube config failed: ${error.message}`);
		process.exit(1);
	}
}
